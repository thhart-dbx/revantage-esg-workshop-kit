import "server-only";
import type { Invoice } from "./types";

// Mock mode only: a one-page PDF rendering of the invoice so the review layout can be built and
// tested before the real PDFs exist in the volume.

const esc = (s: string) => s.replace(/[^\x20-\x7e]/g, "?").replace(/([\\()])/g, "\\$1");

export function mockInvoicePdf(inv: Invoice): Uint8Array {
  const lines: [number, number, string][] = [
    [18, 760, inv.supplier_name ?? "(supplier)"],
    [11, 735, inv.site_address ?? ""],
    [14, 690, "INVOICE"],
    [11, 665, `Invoice no: ${inv.invoice_number ?? ""}`],
    [11, 648, `Invoice date: ${inv.invoice_date ?? ""}`],
    [11, 631, `Billing period: ${inv.billing_period_start ?? ""} - ${inv.billing_period_end ?? ""}`],
    [11, 614, `Meter: ${inv.meter_id ?? ""}   Utility: ${inv.utility_type ?? ""}`],
    [11, 580, `Consumption: ${inv.consumption ?? ""} ${inv.consumption_unit ?? ""}`],
    [11, 545, `Net amount: ${inv.amount_net ?? ""} ${inv.currency ?? ""}`],
    [11, 528, `VAT: ${inv.vat_amount ?? ""} ${inv.currency ?? ""}`],
    [13, 505, `TOTAL: ${inv.amount_total ?? ""} ${inv.currency ?? ""}`],
    [9, 80, "MOCK DOCUMENT - generated by the QA app in mock mode"],
  ];
  const content = lines.map(([size, y, text]) => `BT /F1 ${size} Tf 60 ${y} Td (${esc(text)}) Tj ET`).join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((o, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return new TextEncoder().encode(pdf);
}
